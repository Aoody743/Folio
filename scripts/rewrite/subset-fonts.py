#!/usr/bin/env python3
"""Build offline variable Chinese font subsets; install fonttools[woff] to regenerate."""
from pathlib import Path
import copy
import logging
from fontTools import subset
from fontTools.ttLib import TTFont

logging.getLogger('fontTools').setLevel(logging.ERROR)
ROOT = Path(__file__).resolve().parents[2]

def ranges(values):
    result=[]
    for value in sorted(values):
        if result and value==result[-1][1]+1:
            result[-1][1]=value
        else:
            result.append([value,value])
    return ','.join(f'U+{a:X}' if a==b else f'U+{a:X}-{b:X}' for a,b in result)

source=''.join(p.read_text() for p in (ROOT/'frontend/src').rglob('*.ts*'))
common={ord(c) for c in source if ord(c)>127} | set(range(32,127))
faces=[]
for slug,family in [('noto-sans-sc','Folio Sans SC'),('noto-serif-sc','Folio Serif SC')]:
    original=TTFont(ROOT/'assets/fonts'/f'{slug}.woff2',recalcTimestamp=False)
    supported=set(original.getBestCmap())
    base=supported & common
    remaining=sorted(supported-base)
    groups=[('base',base)]+[(f'extra-{n//2048:02}',set(remaining[n:n+2048])) for n in range(0,len(remaining),2048)]
    folder=ROOT/'frontend/public/fonts'/slug
    folder.mkdir(exist_ok=True)
    for stale in folder.glob('*.woff2'): stale.unlink()
    covered=set()
    for name,chars in groups:
        font=copy.deepcopy(original)
        options=subset.Options()
        options.recalc_timestamp=False
        worker=subset.Subsetter(options=options)
        worker.populate(unicodes=chars)
        worker.subset(font)
        font.flavor='woff2'
        font.save(folder/f'{name}.woff2')
        assert set(font.getBestCmap())==chars, (slug,name,'cmap mismatch')
        assert not (covered & chars), (slug,name,'overlap')
        covered |= chars
        faces.append(f'@font-face {{\n  font-family: "{family}";\n  src: url("/fonts/{slug}/{name}.woff2") format("woff2");\n  font-weight: 100 900;\n  font-display: swap;\n  unicode-range: {ranges(chars)};\n}}\n')
    assert covered==supported, (slug,'missing characters')
    print(slug, 'subsets:',len(groups),'base bytes:',(folder/'base.woff2').stat().st_size,flush=True)
(ROOT/'frontend/src/app/font-subsets.css').write_text('/* Generated by scripts/rewrite/subset-fonts.py; SIL OFL 1.1. */\n'+''.join(faces))
